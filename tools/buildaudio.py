"""Package generated audio (art/audio/<name>/*.mp3, made with ElevenLabs) for the game.
python tools/buildaudio.py
- one-shot SFX are embedded as data URIs in js/audio_assets.js (decoded into WebAudio buffers at runtime)
- music beds are copied to assets/music/<biome>.mp3 and streamed by <audio> elements"""
import os, glob, json, base64, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'art', 'audio')
MUS = os.path.join(ROOT, 'assets', 'music')
os.makedirs(MUS, exist_ok=True)
sounds, music = {}, []
music = [os.path.splitext(f)[0] for f in sorted(os.listdir(MUS)) if f.endswith('.mp3')]
for d in sorted(os.listdir(SRC)):
    files = sorted(glob.glob(os.path.join(SRC, d, '*.mp3')))
    if not files:
        continue
    f = files[-1]  # newest take
    if d.startswith('music_'):
        name = d[6:]
        shutil.move(f, os.path.join(MUS, name + '.mp3'))  # keep a single copy
        if name not in music: music.append(name)
    else:
        sounds[d] = 'data:audio/mpeg;base64,' + base64.b64encode(open(f, 'rb').read()).decode()
        os.makedirs(os.path.join(ROOT, 'assets', 'sfx'), exist_ok=True); shutil.copyfile(f, os.path.join(ROOT, 'assets', 'sfx', d + '.mp3'))
with open(os.path.join(ROOT, 'js', 'audio_assets.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/buildaudio.py — recorded/generated SFX as data URIs, plus the list of music beds.\n')
    out.write('(function (AS) { AS.SOUNDS = ' + json.dumps(sounds) + '; })(AS);\n')
with open(os.path.join(ROOT, 'js', 'audio_manifest.js'), 'w', encoding='utf-8') as out:
    out.write('// Generated by tools/buildaudio.py — sound names (assets/sfx/*.mp3) and music beds (assets/music/*.mp3).\n')
    out.write('(function (AS) { AS.SOUND_FILES = ' + json.dumps(sorted(sounds)) + ';\n  AS.MUSIC = ' + json.dumps(music) + '; })(AS);\n')
print(len(sounds), 'sfx,', len(music), 'music:', music, round(sum(len(v) for v in sounds.values()) / 1e3), 'KB')
